# grade-receipt.sh [--check]
#
# Writes (or checks) verification/receipts/agda-grade3.a2ml: the machine
# record that this repository's Agda claims are at mathesis Grade 3 and nothing
# more.
#
#   Grade 3 (mathesis estate-mathematical-architecture §5): the proof
#   type-checks locally in Agda under strict flags and has NOT been translated
#   to an independent foundational system.
#
# The receipt is DERIVED from the tree, never typed by hand, except for the
# claim list below, which is cross-checked against the claim IDs in
# PROOF-STATUS.adoc in both directions.  That makes two drifts impossible:
#   * a module added or changed without the receipt following it, and
#   * a claim added to PROOF-STATUS.adoc without a ledger token and a grade.
#
# What the receipt deliberately does NOT do: it does not run Agda.  It records
# the gate, the flags and the pinned versions; the gate itself runs in CI
# (.github/workflows/proofs.yml) and its log is the execution evidence.  A
# receipt is a statement about which gate produced which result, not a
# substitute for the result — standards/3-practice/PROOF-POLICY.adoc §2.3.
set -euo pipefail
cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.."
. scripts/proof-flags.sh

out=verification/receipts/agda-grade3.a2ml
mode=
commit_override=
while (( $# )); do
  case "$1" in
    --write|--check) mode="$1" ;;
    --commit)        commit_override="${2:-}"; shift ;;
    -h|--help)
      printf 'usage: %s [--write|--check] [--commit <sha>]\n' "${0##*/}"
      printf '  --commit records a specific revision instead of HEAD (CI does this,\n'
      printf '           because a committed receipt can only name its parent)\n'
      exit 0 ;;
    *) printf 'unknown argument: %s\n' "$1" >&2; exit 2 ;;
  esac
  shift
done

# ── The claim list ────────────────────────────────────────────────────────────
# id | ledger token (README-EXPLAINME-STANDARD §5 vocabulary) | mathesis grade |
# Rocq leg (PROOF-POLICY §2) | Lean leg.
# Tokens are the closed vocabulary: proven | proven-with-postulates | tested-only
# | argued | open.  Legs are: transported | re-proved | unavailable.
claims() {
  cat <<'ROWS'
N-1|proven|grade-3|unavailable|unavailable
N-2|proven|grade-3|unavailable|unavailable
N-3|proven|grade-3|unavailable|unavailable
N-4|tested-only|below-grade-3|n/a|n/a
N-5|tested-only|below-grade-3|n/a|n/a
N-6|tested-only|below-grade-3|n/a|n/a
N-7|proven|grade-3|unavailable|unavailable
N-8|proven|grade-3|unavailable|unavailable
ROWS
}

# ── Derived facts ─────────────────────────────────────────────────────────────
repo="hyperpolymath/secret-types"
uuid="462660d5-8b7e-5bfb-a72c-a942273aa064"   # uuid5(URL, github.com/<repo>)
source_commit="${commit_override:-$(git rev-parse --short=12 HEAD 2>/dev/null || printf 'unknown')}"
agda_version="$(proof_agda_pin)"
agda_from="$(proof_agda_provenance)"
flag_line="$(proof_flags_line)"

# Print the Agda module paths under src/SecretTypes in sorted order.
modules() { find src/SecretTypes -name '*.agda' | LC_ALL=C sort; }
# Print the Agda rejection fixture paths under tests/reject in sorted order.
fixtures() { find tests/reject -name '*.agda' | LC_ALL=C sort; }

# Print matching escape-hatch lines with paths and line numbers from Agda files
# in the gated trees. Suppress grep errors and return success even with no hits.
escape_hits() {
  grep -rn --include='*.agda' -E \
    '(^|[^A-Za-z])(postulate|believe_me|trustMe|sorry|Admitted)([^A-Za-z]|$)|{-# *(TERMINATING|NON_TERMINATING) *#-}|--type-in-type' \
    src/SecretTypes tests 2>/dev/null || true
}

# The claim list and PROOF-STATUS.adoc must name exactly the same claims.
# PROOF-STATUS is the human record; this receipt is the machine one; a claim in
# one and not the other is drift, in either direction.
# Exit with an error if claim IDs cannot be read or differ.
check_claim_ids() {
  local decl doc
  decl="$(claims | cut -d'|' -f1 | LC_ALL=C sort)"
  doc="$(grep -oE '^\| N-[0-9]+ ' PROOF-STATUS.adoc | tr -d '| ' | LC_ALL=C sort -u)"
  if [[ -z "$doc" ]]; then
    echo 'ERROR: no claim ids found in PROOF-STATUS.adoc; the table layout changed' >&2
    exit 1
  fi
  if [[ "$decl" != "$doc" ]]; then
    echo 'ERROR: claim ids differ between this receipt and PROOF-STATUS.adoc' >&2
    diff <(printf '%s\n' "$doc") <(printf '%s\n' "$decl") \
      | sed 's/^</  only in PROOF-STATUS.adoc:/; s/^>/  only in grade-receipt.sh:/' >&2
    exit 1
  fi
}

# Print the derived receipt, including claim rows, module hashes and fixtures.
emit() {
  printf '# SPDX-License-Identifier: CC-BY-SA-4.0\n'
  printf '# SPDX-FileCopyrightText: 2026 Jonathan D.A. Jewell (hyperpolymath)\n'
  printf '#\n'
  printf '# GENERATED by scripts/grade-receipt.sh — do not hand-edit.\n'
  printf '# Regenerate: bash scripts/grade-receipt.sh --write   Check: --check\n'
  printf '#\n'
  printf '# A verification receipt in the sense of mathesis\n'
  printf '# estate-mathematical-architecture §6: it names the exact gate, the exact\n'
  printf '# pin and the exact commit the result belongs to.  It is not a proof and it\n'
  printf '# does not substitute for the CI log.\n'
  printf '\n[identity]\n'
  printf 'repository = "%s"\n' "$repo"
  printf 'uuid = "%s"\n' "$uuid"
  printf 'uuid-source = "uuid5(URL, github.com/%s)"\n' "$repo"
  printf 'uuid-note = "CLADE.a2ml still carries the RSR template uuid — finding F-1, open"\n'
  printf 'kind = "theory"\n'
  printf 'source-commit = "%s"\n' "$source_commit"
  printf '\n[prover]\n'
  printf 'tool = "agda"\n'
  printf 'version = "%s"\n' "$agda_version"
  printf 'provenance = "%s"\n' "$agda_from"
  printf 'library = "none (--no-libraries; Agda builtins only)"\n'
  printf 'flags = "%s"\n' "$flag_line"
  printf 'flags-source = "scripts/proof-flags.sh"\n'
  printf 'flags-note = "one definition, read by the gate and by this receipt; the receipt cannot describe a gate that did not run"\n'
  printf '\n[conformance]\n'
  printf 'policy = "standards/3-practice/PROOF-POLICY.adoc"\n'
  printf 'policy-revision = "owner ruling 2026-10-26; section 2.1 dated 2026-11-01"\n'
  printf 'canonical-invocation = "agda --safe --without-K --cubical-compatible"\n'
  printf 'cubical-compatible = "waived"\n'
  printf 'waiver-ref = "docs/proof-debt.adoc#waivers"\n'
  printf 'waiver-reason = "every clause matching on the order relation is an indexed match, which Cubical Agda does not support; suppressing -WUnsupportedIndexedMatch would be a green gate over a weakened check"\n'
  printf 'stronger-than-canonical = ["--no-libraries", "--ignore-interfaces", "--double-check", "-W error"]\n'
  printf '\n[gate]\n'
  printf 'command = "bash scripts/check.sh"\n'
  printf 'laws-certificate = "bash scripts/minimal-laws.sh"\n'
  printf 'ci = ".github/workflows/proofs.yml"\n'
  printf 'module-count = %s\n' "$(modules | wc -l | tr -d ' ')"
  printf 'reject-fixture-count = %s\n' "$(fixtures | wc -l | tr -d ' ')"
  printf '\n[trust-base]\n'
  printf 'postulates = %s\n' "$(grep -rlw --include='*.agda' postulate src/SecretTypes tests 2>/dev/null | wc -l | tr -d ' ')"
  printf 'escape-hatches = %s\n' "$(escape_hits | wc -l | tr -d ' ')"
  printf 'library-dependencies = 0\n'
  printf 'axioms-assumed = 0\n'
  printf 'note = "a non-zero count above fails the gate; the receipt is only meaningful while all four are zero"\n'
  printf '\n[[claims]]\n'
  printf '# id | ledger token | mathesis grade | coq-leg | lean-leg\n'
  printf '# mathesis grades theorems.  A refusal fixture or a witness of a leak is a\n'
  printf '# checked demonstration, not a theorem, so it is below-grade-3 rather than\n'
  printf '# graded — the token still says exactly how strongly it is checked.\n'
  printf '# Legs are unavailable for every proven row: no Agda→Dedukti transport has\n'
  printf '# been attempted from this repository and no hand re-proof exists.  Per\n'
  printf '# PROOF-POLICY §2.3 that keeps each row at Grade 3 and no higher; see\n'
  printf '# PROOF-STATUS.adoc "Grade and the independent-witness legs".\n'
  while IFS='|' read -r id token grade coq lean; do
    printf 'claim = { id = "%s", token = "%s", grade = "%s", coq-leg = "%s", lean-leg = "%s" }\n' \
      "$id" "$token" "$grade" "$coq" "$lean"
  done < <(claims)
  printf '\n[modules]\n'
  printf '# sha256 of each module, so a change to a proved statement cannot leave the\n'
  printf '# receipt intact.  --check compares these.\n'
  while read -r m; do
    printf 'module = { path = "%s", sha256 = "%s" }\n' "$m" "$(sha256sum "$m" | cut -d' ' -f1)"
  done < <(modules)
  printf '\n[fixtures]\n'
  while read -r f; do
    printf 'fixture = "%s"\n' "$f"
  done < <(fixtures)
}

check_claim_ids

case "$mode" in
  --write|"")
    mkdir -p "$(dirname "$out")"
    emit > "$out"
    printf 'WROTE %s (source-commit %s)\n' "$out" "$source_commit"
    ;;
  --check)
    tmp="$(mktemp)"; trap 'rm -f "$tmp"' EXIT
    emit > "$tmp"
    # The source-commit line is expected to differ: a receipt is committed by
    # the change that produces it and so records its parent.  Everything else
    # must match byte for byte, including every module sha256.
    # Print the receipt file in $1 without its source-commit line.
    filter() { grep -v '^source-commit = ' "$1"; }
    if ! diff -u <(filter "$out") <(filter "$tmp") > /tmp/receipt-diff.$$ 2>&1; then
      echo 'ERROR: verification receipt does not match the tree:' >&2
      sed -n '1,60p' /tmp/receipt-diff.$$ >&2
      rm -f /tmp/receipt-diff.$$
      echo 'Regenerate with: bash scripts/grade-receipt.sh --write' >&2
      exit 1
    fi
    rm -f /tmp/receipt-diff.$$
    echo "PASS: verification receipt matches the tree ($(modules | wc -l | tr -d ' ') modules, all sha256 verified)"
    ;;
  *)
    echo "usage: ${0##*/} [--write|--check]" >&2
    exit 2
    ;;
esac
